# Explique o funcionamento dos comandos print e input. Dê ao menos três
# exemplos de cada

# Print: o comando print é muito usado na programação porque ele mostra qualquer coisa no terminal, ele imprime (print em ingles) o que for pedido dentro dele.
# Exemplo 1:
print("Olá mundo")
# Aqui nos pedimos para que seja impresso a frase "Olá mundo", o print irá converter automaticamente para str o que foi digitado dentro se estiver com "" do contrario ele irá dar procurar uma variavel com o mesmo nome para executar.
# Exemplo 2:
variavel = "Sou uma variavel @_@"
print(variavel)
# Nesse exemplo o print irá mostrar no terminal o conteudo que foi armazenado na variavel.
# Exemplo 3:
print(2+1)
# Também é possivel executar contas simples dentro do print ele as realiza de forma rápida. Se você não usar "", o computador fará a conta matemática primeiro e exibirá apenas o resultado.
